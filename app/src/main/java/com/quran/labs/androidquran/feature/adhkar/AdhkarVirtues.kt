package com.quran.labs.androidquran.feature.adhkar

/** One point of a virtue; [label] says when it applies, e.g. "في النهار". */
data class VirtuePoint(val label: String?, val text: String)

/** The reward the Sunnah promises for a dhikr, in the hadith's words, and where it is narrated. */
data class DhikrVirtue(val points: List<VirtuePoint>, val source: String)

/**
